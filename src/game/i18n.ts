const TRANSLATIONS: Record<LanguageCode, FullDict> = {
  en: EN_DICT,
  uz: UZ_DICT,
  ru: RU_DICT,
  ...EXTRA_LOCALES,
};

export function normalizeLangCode(code?: string | null): LanguageCode {
  if (!code) return 'en';
  const found = LANGUAGES.find((l) => l.code === code);
  return found ? found.code : 'en';
}

export function getLanguageDef(code?: string | null): LanguageDef {
  const norm = normalizeLangCode(code);
  return LANGUAGES.find((l) => l.code === norm) ?? LANGUAGES[0];
}

export function isRtlLanguage(code?: string | null): boolean {
  return Boolean(getLanguageDef(code).rtl);
}

export function tr(
  lang: string | null | undefined,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const code = normalizeLangCode(lang);
  const extraDict = MASTER_EXTRAS_BY_LANG[code] as Record<string, string> | undefined;
  const baseDict = TRANSLATIONS[code] as Record<string, string> | undefined;
  const enExtra = EN_MASTER_EXTRAS as Record<string, string>;
  const enBase = EN_DICT as Record<string, string>;
  let text: string =
    extraDict?.[key] ?? baseDict?.[key] ?? enExtra[key] ?? enBase[key] ?? String(key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}
