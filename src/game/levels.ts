function charToTile(ch: string): TileKind {
  switch (ch) {
    case '#':
      return 1;
    case '=':
      return 2;
    case '^':
      return 3;
    case 'I':
      return 4;
    case '|':
      return 5;
    case '?':
      return 6;
    case 'M':
      return 7;
    case '~':
      return 8;
    case 'w':
      return 9;
    default:
      return 0;
  }
}

function parseAsciiMap(rows: string[]): TileKind[][] {
  const width = Math.max(...rows.map((r) => r.length));
  return rows.map((r) => {
    const padded = r.padEnd(width, '.');
    return Array.from(padded).map(charToTile);
  });
}

const T = TILE_SIZE;
const pt = (tx: number, ty: number) => ({ x: tx * T + T / 2, y: ty * T + T / 2 });

interface StageBuildInput {
  id: string;
  worldId: WorldId;
  stageNumber: number;
  name: string;
  isBossStage?: boolean;
  bossType?: StageDef['bossType'];
  bossName?: string;
  ascii: string[];
  spawnTile: [number, number];
  exitTile: [number, number];
  checkpoints?: [number, number][];
  movingPlatforms?: MovingPlatformDef[];
  swingAnchors?: [number, number][];
  portals?: PortalPairDef[];
  enemies?: EnemySpawnDef[];
  collectibles?: CollectibleDef[];
  crates?: CrateDef[];
  shrines?: ShrineDef[];
  fallingRocks?: [number, number][];
  tutorialHint?: string;
}

function buildStage(cfg: StageBuildInput): StageDef {
  const tiles = parseAsciiMap(cfg.ascii);
  return {
    id: cfg.id,
    worldId: cfg.worldId,
    stageNumber: cfg.stageNumber,
    name: cfg.name,
    isBossStage: Boolean(cfg.isBossStage),
    bossType: cfg.bossType,
    bossName: cfg.bossName,
    widthTiles: tiles[0].length,
    heightTiles: tiles.length,
    tiles,
    spawn: pt(cfg.spawnTile[0], cfg.spawnTile[1]),
    exit: pt(cfg.exitTile[0], cfg.exitTile[1]),
    checkpoints: (cfg.checkpoints ?? []).map(([x, y]) => pt(x, y)),
    movingPlatforms: cfg.movingPlatforms ?? [],
    swingAnchors: (cfg.swingAnchors ?? []).map(([x, y]): SwingAnchorDef => pt(x, y)),
    portals: cfg.portals ?? [],
    enemies: cfg.enemies ?? [],
    collectibles: cfg.collectibles ?? [],
    crates: cfg.crates ?? [],
    shrines: cfg.shrines ?? [],
    fallingRocks: (cfg.fallingRocks ?? []).map(([x, y]): FallingRockDef => pt(x, y)),
    tutorialHint: cfg.tutorialHint,
  };
}

