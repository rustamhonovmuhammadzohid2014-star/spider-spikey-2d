export function getSkinMinLevel(skin: SkinDef): number {
  if (typeof skin.minPlayerLevel === 'number') return skin.minPlayerLevel;
  switch (skin.rarity) {
    case 'common':
      return 1;
    case 'uncommon':
      return 2;
    case 'rare':
      return 4;
    case 'epic':
      return 6;
    case 'legendary':
      return 10;
    case 'mythic':
      return 14;
    case 'limited':
      return 8;
    default:
      return 1;
  }
}

// Normalize category mapping so Mythic, Legendary, and ZAI Limited skins filter accurately
export function getSkinById(id: string | undefined | null): SkinDef {
  if (!id) return ALL_SKINS[0];
  return ALL_SKINS.find((s) => s.id === id) ?? ALL_SKINS[0];
}

export function skinMatchesCategory(skin: SkinDef, category: SkinCategory): boolean {
  if (category === 'all') return true;
  if (category === 'legendary') return skin.rarity === 'legendary';
  if (category === 'mythic') return skin.rarity === 'mythic';
  if (category === 'seasonal') return skin.category === 'seasonal';
  if (category === 'zai') return Boolean(skin.isZaiLimited || skin.category === 'zai');
  if (category === 'limited') return skin.rarity === 'limited' || Boolean(skin.isZaiLimited);
  return skin.category === category;
}

export function starterColorToSkinId(color: SpiderColorId | string | undefined): string {
  if (!color) return 'classic';
  if (ALL_SKINS.some((s) => s.id === color)) return color;
  return 'classic';
}
